SET s.price = (CASE 
    WHEN t.route_id IN (1, 2, 9, 10, 11, 12, 19, 20) THEN 650000 
    WHEN t.route_id IN (3, 4, 15, 16, 23, 24, 27, 28) THEN 450000 
    ELSE 250000 END) 
    + (CASE WHEN s.floor = 2 THEN 50000 ELSE 0 END)
WHERE s.price = 0;

