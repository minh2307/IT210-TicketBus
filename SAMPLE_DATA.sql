-- Using direct INSERT statements instead of stored procedure for better compatibility

-- Generate seats for trips that don't have seats yet
INSERT INTO seats (seat_number, floor, status, trip_id, price, version)
WITH RECURSIVE seat_numbers AS (
    SELECT 
        t.id as trip_id,
        b.bus_type,
        b.total_seats,
        1 as seat_num
    FROM trips t
    JOIN buses b ON t.bus_id = b.id
    WHERE t.id NOT IN (SELECT DISTINCT trip_id FROM seats)
    
    UNION ALL
    
    SELECT 
        trip_id,
        bus_type,
        total_seats,
        seat_num + 1
    FROM seat_numbers
    WHERE seat_num < total_seats
)
SELECT 
    CASE 
        WHEN bus_type LIKE 'SLEEPER%' AND seat_num > (total_seats / 2) 
        THEN CONCAT('B', LPAD(seat_num - (total_seats / 2), 2, '0'))
        ELSE CONCAT('A', LPAD(seat_num, 2, '0'))
    END as seat_number,
    CASE 
        WHEN bus_type LIKE 'SLEEPER%' AND seat_num > (total_seats / 2) THEN 2
        ELSE 1
    END as floor,
    'AVAILABLE' as status,
    trip_id,
    0 as price,
    0 as version
FROM seat_numbers;

